// Scene state: the loaded models (each with its own motion), the scene-level camera motion
// and the audio track. Owns GPU / physics resources and releases them on removal.

/** One auxiliary map for custom material shaders: generated by the app or loaded from a file. */
export interface AuxMap {
  name: string;
  generated: boolean;
  /** The image file (PNG for generated maps), kept for saving with a project. */
  blob: Blob;
  texture: GPUTexture;
}

export type AuxSlot = 'ramp' | 'light' | 'face';

/** A model's auxiliary maps: one ramp, and a light map / face map per base texture (by texture index). */
export interface ModelAux {
  ramp: AuxMap | null;
  light: Map<number, AuxMap>;
  face: Map<number, AuxMap>;
}

/** How far cloth vertices are kept outside the body's colliders (model units, about 3 mm). */
const CLOTH_MARGIN = 0.04;

let nextId = 1;

export class SceneModel {
  readonly id = nextId++;
  visible = true;
  motion: MmdMotion | null = null;
  /** Files merged into `motion`, in import order. */
  motionNames: string[] = [];
  /**
   * How the motion fits this model, counting only tracks that do something (motions often carry
   * a do-nothing key for every bone and morph of the model they were made with): how many are
   * used, how many of those this model has, and the names it lacks.
   */
  binding: { bones: number; usedBones: number; morphs: number; usedMorphs: number; missingBones: string[]; missingMorphs: string[] } | null = null;
  /** Precomputed physics for the current motion (replaces live physics while `useBake`). */
  bake: PhysicsBake | null = null;
  useBake = true;
  /** Where the model stands in the scene: offset and rotation about the vertical axis (degrees). */
  position: [number, number, number] = [0, 0, 0];
  rotationY = 0;

  /** Auxiliary maps custom material shaders can read. Change through setAux / clearAux. */
  aux: ModelAux = { ramp: null, light: new Map(), face: new Map() };

  /** Material indices the user hid (a hat, the shoes…). Change through the setters below. */
  readonly hiddenMaterials = new Set<number>();

  setMaterialVisible(index: number, visible: boolean): void {
    if (visible) this.hiddenMaterials.delete(index);
    else this.hiddenMaterials.add(index);
    this.gpu.setHiddenMaterials(this.hiddenMaterials);
  }

  setHiddenMaterials(indices: Iterable<number>): void {
    this.hiddenMaterials.clear();
    for (const i of indices) this.hiddenMaterials.add(i);
    this.gpu.setHiddenMaterials(this.hiddenMaterials);
  }

  get hasAux(): boolean {
    return !!this.aux.ramp || this.aux.light.size > 0 || this.aux.face.size > 0;
  }

  /** Install a map (the model takes ownership of its texture). `textureIndex` is ignored for the ramp. */
  setAux(slot: AuxSlot, textureIndex: number, map: AuxMap): void {
    if (slot === 'ramp') {
      this.aux.ramp?.texture.destroy();
      this.aux.ramp = map;
    } else {
      this.aux[slot].get(textureIndex)?.texture.destroy();
      this.aux[slot].set(textureIndex, map);
    }
    this.bindAux();
  }

  clearAux(slot: AuxSlot, textureIndex: number): void {
    if (slot === 'ramp') {
      this.aux.ramp?.texture.destroy();
      this.aux.ramp = null;
    } else {
      this.aux[slot].get(textureIndex)?.texture.destroy();
      this.aux[slot].delete(textureIndex);
    }
    this.bindAux();
  }

  /** Hand the maps to another instance of the same model (after a rebuild). */
  moveAuxTo(other: SceneModel): void {
    other.aux = this.aux;
    this.aux = { ramp: null, light: new Map(), face: new Map() };
    other.bindAux();
  }

  private bindAux(): void {
    const { aux } = this;
    const perMaterial: AuxTextures[] = this.pmx.materials.map((m) => ({
      ramp: aux.ramp?.texture ?? null,
      light: aux.light.get(m.textureIndex)?.texture ?? null,
      face: aux.face.get(m.textureIndex)?.texture ?? null,
    }));
    this.gpu.setAuxTextures(this.hasAux ? perMaterial : null);
  }

  /** Custom material shader in use (null = MMD's shading). Set through App.setModelShader. */
  shader: CustomShader | null = null;

  /** Scale of the motion's bone translations, to fit this model's leg length. */
  get motionScale(): number {
    return this.model.motionScale;
  }

  /** Returns true if that invalidated a physics bake. */
  setMotionScale(scale: number): boolean {
    if (scale === this.model.motionScale) return false;
    this.model.motionScale = scale;
    return this.dropBake();
  }

  /**
   * Proportions relative to the standard MMD model (あにまさ式ミク, which most motions and
   * camera work are made for): leg length (hip to ankle ≈ 9.6) and head height (≈ 17).
   * null where the model lacks the standard bones.
   */
  get proportions(): { legs: number | null; head: number | null } {
    const y = (name: string) => this.pmx.bones.find((b) => b.name === name)?.position[1];
    const hip = y('左足'), ankle = y('左足首'), head = y('頭');
    return {
      legs: hip !== undefined && ankle !== undefined && hip > ankle ? (hip - ankle) / 9.6 : null,
      head: head !== undefined && head > 0 ? head / 17 : null,
    };
  }

  constructor(
    readonly name: string,
    /** Where the model's files come from (textures are re-read from here on export / save). */
    readonly source: AssetSource,
    /** Path of the PMX / PMD within `source`. */
    readonly path: string,
    /** The model file exactly as imported. */
    readonly fileBytes: ArrayBuffer,
    readonly pmx: PmxModel,
    readonly model: MmdModel,
    readonly gpu: GpuModel,
    readonly textures: TextureScope,
    readonly rig: PhysicsRig | null,
    readonly missingTextures: string[],
  ) {}

  get baseDir(): string {
    return dirname(this.path);
  }

  /** Merge a VMD into the motion. Returns true if that invalidated a physics bake. */
  addMotion(name: string, vmd: VmdMotion): boolean {
    this.motion ??= new MmdMotion();
    this.motion.merge(vmd);
    this.motionNames.push(name);
    this.bind();
    return this.dropBake();
  }

  /** Replace the motion. Returns true if that invalidated a physics bake. */
  setMotion(motion: MmdMotion | null, names: string[]): boolean {
    this.motion = motion;
    this.motionNames = names;
    this.bind();
    return this.dropBake();
  }

  /** Move / turn the whole model. Physics should be reset afterwards. */
  setTransform(position: [number, number, number], rotationY: number): void {
    this.position = position;
    this.rotationY = rotationY;
    const q = quat.fromAxisAngle(quat.create(), [0, 1, 0], (rotationY * Math.PI) / 180);
    mat4.fromRotationTranslation(this.model.skeleton.root, q, vec3.create(...position));
  }

  /** A bake belongs to the motion it was made with. */
  private dropBake(): boolean {
    const had = this.bake !== null;
    this.bake = null;
    return had;
  }

  private bind(): void {
    this.model.setMotion(this.motion);
    const motion = this.motion;
    if (!motion) {
      this.binding = null;
      return;
    }
    const boneNames = new Set(this.pmx.bones.flatMap((b) => [b.name, vmdName(b.name)]));
    const morphNames = new Set(this.pmx.morphs.flatMap((m) => [m.name, vmdName(m.name)]));
    const usedBones = [...motion.boneTracks].filter(([, t]) =>
      t.frames.length > 1 || t.positions.some((v) => Math.abs(v) > 1e-6) || Math.abs(t.rotations[3]) < 1 - 1e-6).map(([name]) => name);
    const usedMorphs = [...motion.morphTracks].filter(([, t]) => t.weights.some((w) => Math.abs(w) > 1e-6)).map(([name]) => name);
    const missingBones = usedBones.filter((n) => !boneNames.has(n));
    const missingMorphs = usedMorphs.filter((n) => !morphNames.has(n));
    this.binding = {
      usedBones: usedBones.length, bones: usedBones.length - missingBones.length, missingBones,
      usedMorphs: usedMorphs.length, morphs: usedMorphs.length - missingMorphs.length, missingMorphs,
    };
  }

  dispose(): void {
    this.model.attachPhysics(null);
    this.aux.ramp?.texture.destroy();
    for (const map of [...this.aux.light.values(), ...this.aux.face.values()]) map.texture.destroy();
    this.gpu.destroy();
    this.textures.destroy();
  }
}

async function loadMaterialTextures(scope: TextureScope, core: RendererCore, source: AssetSource, baseDir: string, pmx: PmxModel): Promise<MaterialTextures[]> {
  const path = (i: number) => (i >= 0 && i < pmx.textures.length ? pmx.textures[i] : null);
  return Promise.all(
    pmx.materials.map(async (m) => {
      const texPath = path(m.textureIndex);
      const spherePath = m.sphereMode !== SphereMode.None ? path(m.sphereTextureIndex) : null;
      const toonPath = m.sharedToon ? null : path(m.toonIndex);
      const [texture, sphere, toonFile] = await Promise.all([
        texPath ? scope.load(source, baseDir, texPath, { mipmaps: true }) : null,
        spherePath ? scope.load(source, baseDir, spherePath, { mipmaps: m.sphereMode === SphereMode.SubTexture }) : null,
        toonPath ? scope.load(source, baseDir, toonPath, { mipmaps: false }) : null,
      ]);
      const toon = m.sharedToon ? (core.textures.sharedToons[m.toonIndex] ?? null) : toonFile;
      return { texture, sphere, toon };
    }),
  );
}

/** Parse a PMX / PMD, load its textures and build its runtime + GPU resources. */
export async function loadSceneModel(core: RendererCore, source: AssetSource, path: string, fileBytes: ArrayBuffer): Promise<SceneModel> {
  const ext = extname(path);
  const pmx = ext === 'pmd' ? parsePmd(fileBytes) : ext === 'x' ? parseX(fileBytes, basename(path)) : parsePmx(fileBytes);
  const scope = core.textures.createScope();
  try {
    const baseDir = dirname(path);
    const textures = await loadMaterialTextures(scope, core, source, baseDir, pmx);
    const model = new MmdModel(pmx, textures.map((t) => ({ hasTexture: !!t.texture, hasSphere: !!t.sphere, hasToon: !!t.toon })));
    const rig = pmx.rigidBodies.length > 0 ? buildPhysicsRig(physicsModelData(pmx)) : null;
    const cloth = rig ? buildClothCollision(pmx, rig, CLOTH_MARGIN) : null;
    const gpu = new GpuModel(core, model, textures, cloth && rig ? { data: cloth, rig } : null);
    const missing = pmx.materials
      .filter((m, i) => m.textureIndex >= 0 && m.textureIndex < pmx.textures.length && !textures[i].texture)
      .map((m) => pmx.textures[m.textureIndex]);
    return new SceneModel(pmx.name || basename(path), source, path, fileBytes, pmx, model, gpu, scope, rig, [...new Set(missing)]);
  } catch (err) {
    scope.destroy();
    throw err;
  }
}

export interface SceneAudio {
  name: string;
  blob: Blob;
  url: string;
}

export class Scene {
  readonly models: SceneModel[] = [];
  selectedId: number | null = null;
  /** Camera / light / self-shadow motion (scene level, like MMD's camera track). */
  cameraMotion: MmdMotion | null = null;
  cameraNames: string[] = [];
  audio: SceneAudio | null = null;
  /** Panorama image shown behind everything. */
  background: { name: string; blob: Blob } | null = null;
  /** Custom post-processing shader in use. Set through App.setPostShader. */
  postShader: CustomShader | null = null;
  private readonly listeners = new Set<() => void>();

  onChange(fn: () => void): () => void {
    this.listeners.add(fn);
    return () => this.listeners.delete(fn);
  }

  changed(): void {
    for (const fn of this.listeners) fn();
  }

  get selected(): SceneModel | null {
    return this.models.find((m) => m.id === this.selectedId) ?? null;
  }

  get isEmpty(): boolean {
    return this.models.length === 0 && !this.cameraMotion && !this.audio && !this.background && !this.postShader;
  }

  add(model: SceneModel, select = true): void {
    this.models.push(model);
    if (select || this.selectedId === null) this.selectedId = model.id;
    this.changed();
  }

  remove(id: number): void {
    const i = this.models.findIndex((m) => m.id === id);
    if (i < 0) return;
    const [m] = this.models.splice(i, 1);
    m.dispose();
    if (this.selectedId === id) this.selectedId = this.models[Math.min(i, this.models.length - 1)]?.id ?? null;
    this.changed();
  }

  select(id: number): void {
    if (this.selectedId === id) return;
    this.selectedId = id;
    this.changed();
  }

  addCameraMotion(name: string, vmd: VmdMotion): void {
    this.cameraMotion ??= new MmdMotion();
    this.cameraMotion.merge(vmd);
    this.cameraNames.push(name);
    this.changed();
  }

  clearCameraMotion(): void {
    this.cameraMotion = null;
    this.cameraNames = [];
    this.changed();
  }

  setAudio(name: string, blob: Blob): void {
    this.clearAudio(false);
    this.audio = { name, blob, url: URL.createObjectURL(blob) };
    this.changed();
  }

  clearAudio(notify = true): void {
    if (this.audio) URL.revokeObjectURL(this.audio.url);
    this.audio = null;
    if (notify) this.changed();
  }

  /** Last keyframe across every model motion and the camera. */
  get lastFrame(): number {
    let last = this.cameraMotion?.lastFrame ?? 0;
    for (const m of this.models) last = Math.max(last, m.motion?.lastFrame ?? 0);
    return last;
  }

  clear(): void {
    for (const m of this.models) m.dispose();
    this.models.length = 0;
    this.selectedId = null;
    this.cameraMotion = null;
    this.cameraNames = [];
    this.background = null;
    this.postShader = null;
    this.clearAudio(false);
    this.changed();
  }
}
